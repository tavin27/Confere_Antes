-- [SEG] MENOR PRIVILÉGIO
-- Papéis NOLOGIN: crie os logins reais e faça GRANT app_rw TO seu_login;
-- =====================================================================
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_rw') THEN
        CREATE ROLE app_rw NOLOGIN;           -- backend da aplicação
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_ro') THEN
        CREATE ROLE app_ro NOLOGIN;           -- painel / relatórios (somente leitura)
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'privacy_officer') THEN
        CREATE ROLE privacy_officer NOLOGIN;  -- encarregado de dados (DPO)
    END IF;
END
$$;

