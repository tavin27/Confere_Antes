$fn$;


-- =====================================================================
-- [SEG] VERIFICAÇÃO ATÔMICA DO CÓDIGO (anti força bruta)
-- A aplicação envia o HMAC do código; a comparação, a contagem de tentativas
-- e o bloqueio acontecem numa única operação com lock de linha.
-- =====================================================================
CREATE OR REPLACE FUNCTION verify_transaction_code(
    p_transaction_id UUID,
    p_user_id BIGINT,
    p_code_hash TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $fn$
DECLARE
    t transactions%ROWTYPE;
BEGIN
        SELECT * INTO t
            FROM transactions
         WHERE id = p_transaction_id AND user_id = p_user_id
         FOR UPDATE;

    IF NOT FOUND OR t.status_transaction <> 'pending' OR t.verification_code_hash IS NULL THEN
        RETURN FALSE;
    END IF;

    IF t.verification_code_expires_at < now() THEN
        UPDATE transactions
           SET status_transaction = 'expired',
               verification_code_hash = NULL,
               verification_code_expires_at = NULL
         WHERE id = t.id;
        RETURN FALSE;
    END IF;

    IF t.verification_code_hash = p_code_hash THEN
        UPDATE transactions
           SET status_transaction = 'confirmed',
               confirmed_at = now(),
               verification_code_hash = NULL,          -- minimização: descarta o hash após o uso
               verification_code_expires_at = NULL
         WHERE id = t.id;
        RETURN TRUE;
    END IF;

    IF t.verification_attempts + 1 >= 5 THEN
        UPDATE transactions
           SET verification_attempts = 5,
               status_transaction = 'cancelled',       -- 5 erros: bloqueia a transação
               verification_code_hash = NULL,
               verification_code_expires_at = NULL
         WHERE id = t.id;
    ELSE
        UPDATE transactions
           SET verification_attempts = verification_attempts + 1
         WHERE id = t.id;
    END IF;
    RETURN FALSE;
END;
$fn$;

-- [SEG][LGPD] Job periódico: expira códigos vencidos e descarta o hash (minimização)
CREATE OR REPLACE FUNCTION expire_pending_transactions()
RETURNS INTEGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $fn$
DECLARE
    v_count INTEGER;
BEGIN
    UPDATE transactions
       SET status_transaction = 'expired',
           verification_code_hash = NULL,
           verification_code_expires_at = NULL
     WHERE status_transaction = 'pending'
       AND verification_code_expires_at < now();
    GET DIAGNOSTICS v_count = ROW_COUNT;
    RETURN v_count;
END;
$fn$;


-- =====================================================================
-- [LGPD] DIREITOS DO TITULAR
-- =====================================================================

-- Eliminação/anonimização (art. 18, IV e VI). Usa anonimização em vez de DELETE porque
-- alerts.user_id é RESTRICT e os alertas têm valor para prevenção a fraudes.
-- Mantém: origin_number (número do golpista, tratado para prevenção a fraudes - art. 7º, IX
-- e art. 11, II, g), tipo, valor, canal, categoria e score.
CREATE OR REPLACE FUNCTION anonymize_user(
    p_user_id BIGINT,
    p_bcrypt_hash TEXT,
    p_request_id UUID DEFAULT NULL
)
RETURNS BOOLEAN
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $fn$
BEGIN
    IF p_bcrypt_hash IS NULL OR p_bcrypt_hash !~ '^\$2[aby]\$' THEN
        RAISE EXCEPTION 'A BCrypt hash for a random discarded secret is required';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM users
                    WHERE id = p_user_id AND email NOT LIKE '%@anonimizado.invalid') THEN
        RETURN FALSE;   -- inexistente ou já anonimizado
    END IF;

    UPDATE users
       SET username      = 'anon_' || id,
           email         = 'anon_' || id || '@anonimizado.invalid',
           phone         = NULL,
           password_hash = p_bcrypt_hash,
           active        = FALSE
     WHERE id = p_user_id;

    UPDATE transactions
       SET description_client           = NULL,
           description_transaction      = NULL,
           verification_code_hash       = NULL,
           verification_code_expires_at = NULL,
           status_transaction = CASE WHEN status_transaction = 'pending'
                                     THEN 'cancelled' ELSE status_transaction END
     WHERE user_id = p_user_id;

    UPDATE alerts
       SET description_alert = '[removido a pedido do titular]',
           ai_justification  = NULL
     WHERE user_id = p_user_id;

    UPDATE consents SET revoked_at = now()
     WHERE user_id = p_user_id AND revoked_at IS NULL;

    IF p_request_id IS NOT NULL THEN
        UPDATE privacy_requests
           SET status = 'completed', completed_at = now()
         WHERE id = p_request_id AND user_id = p_user_id;
    END IF;

    INSERT INTO audit_log (actor, action, table_name, record_id, purpose)
    VALUES (session_user::TEXT,
            'ANONYMIZE', 'users', p_user_id::TEXT,
            COALESCE('privacy_request ' || p_request_id::TEXT, 'sem solicitação vinculada'));
    RETURN TRUE;
END;
$fn$;

-- Acesso e portabilidade (art. 18, II e V). Nunca inclui hashes de senha/código
CREATE OR REPLACE FUNCTION export_user_data(p_user_id BIGINT)
RETURNS JSONB
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $fn$
DECLARE
    v_result JSONB;
BEGIN
    SELECT jsonb_build_object(
        'user', (SELECT to_jsonb(u) - 'password_hash' FROM users u WHERE u.id = p_user_id),
        'transactions', COALESCE((SELECT jsonb_agg(to_jsonb(t)
                                   - 'verification_code_hash'
                                   - 'verification_code_expires_at'
                                   - 'verification_attempts')
                                  FROM transactions t WHERE t.user_id = p_user_id), '[]'::jsonb),
        'alerts', COALESCE((SELECT jsonb_agg(to_jsonb(a))
                              FROM alerts a WHERE a.user_id = p_user_id), '[]'::jsonb),
        'consents', COALESCE((SELECT jsonb_agg(to_jsonb(c))
                                FROM consents c WHERE c.user_id = p_user_id), '[]'::jsonb)
    ) INTO v_result;

    INSERT INTO audit_log (actor, action, table_name, record_id, purpose)
    VALUES (session_user::TEXT,
            'EXPORT', 'users', p_user_id::TEXT, 'portabilidade/acesso do titular');
    RETURN v_result;
END;
$fn$;


