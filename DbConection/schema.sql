CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ---------------------------------------------------------------------
-- TABELAS ORIGINAIS
-- ---------------------------------------------------------------------
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    phone VARCHAR(20),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,

    -- [SEG] só aceita hashes bcrypt ($2a/$2b/$2y) ou argon2; impede senha em texto puro
    CONSTRAINT chk_users_password_hash_format
        CHECK (password_hash ~ '^\$(argon2id|argon2i|2[aby])\$')
);

CREATE TABLE transactions (
    id                       UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id                  BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    type_transaction         VARCHAR(40) NOT NULL,   -- 'cancelamento_boleto' | 'correcao_compra' | 'instalacao_app' | 'outro'
    amount                   NUMERIC(12,2),
    description_transaction  TEXT,                    -- descrição gerada pelo sistema
    description_client       TEXT,                    -- relato do próprio usuário
    channel                  VARCHAR(60),             -- 'ligacao' | 'whatsapp' | 'sms' | 'email'
    status_transaction       VARCHAR(20) NOT NULL DEFAULT 'pending',
    verification_code_hash VARCHAR(256),
    verification_code_expires_at TIMESTAMPTZ,
    verification_attempts    SMALLINT NOT NULL DEFAULT 0,
    created_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
    confirmed_at              TIMESTAMPTZ,

    CONSTRAINT chk_transactions_status
        CHECK (status_transaction IN ('pending', 'confirmed', 'cancelled', 'expired')),
    CONSTRAINT chk_transactions_confirmation_time
        CHECK (
            (status_transaction = 'confirmed' AND confirmed_at IS NOT NULL) OR
            (status_transaction <> 'confirmed' AND confirmed_at IS NULL)
        ),
    CONSTRAINT chk_transactions_code_expiry
        CHECK (
            (verification_code_hash IS NULL AND verification_code_expires_at IS NULL) OR
            (verification_code_hash IS NOT NULL AND verification_code_expires_at IS NOT NULL)
        ),
    CONSTRAINT chk_transactions_attempts
        CHECK (verification_attempts BETWEEN 0 AND 5),
    CONSTRAINT chk_transactions_type
        CHECK (type_transaction IN ('cancelamento_boleto', 'correcao_compra', 'instalacao_app', 'outro')),
    CONSTRAINT chk_transactions_amount
        CHECK (amount IS NULL OR amount >= 0),
    CONSTRAINT chk_transactions_channel
        CHECK (channel IS NULL OR channel IN ('ligacao', 'whatsapp', 'sms', 'email')),

    -- [SEG] o hash do código deve ser HMAC-SHA256 em hex (64 caracteres), nunca o código em claro
    CONSTRAINT chk_transactions_code_hash_format
        CHECK (verification_code_hash IS NULL OR verification_code_hash ~ '^[0-9a-f]{64}$')
);

CREATE INDEX idx_transactions_user_recent
    ON transactions (user_id, created_at DESC);

CREATE INDEX idx_transactions_pending_recent
    ON transactions (created_at DESC)
    WHERE status_transaction = 'pending';

CREATE TABLE scam_patterns (
    id          BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    category    VARCHAR(80)  NOT NULL UNIQUE,
    title       VARCHAR(150) NOT NULL,
    description TEXT         NOT NULL,
    keywords    TEXT[]       NOT NULL DEFAULT '{}',
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE alerts (
    id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id            BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    transaction_id     UUID REFERENCES transactions(id),
    pattern_id         BIGINT REFERENCES scam_patterns(id),

    contact_channel    VARCHAR(20) NOT NULL,   -- 'ligacao' | 'whatsapp' | 'sms' | 'email'
    origin_number      VARCHAR(20) NOT NULL,
    description_alert  TEXT NOT NULL,

    scam_category      VARCHAR(80),            -- preenchido pela IA com base no padrão de golpe detectado
    risk_level         VARCHAR(10),            -- 'low' | 'medium' | 'high'
    risk_score         NUMERIC(5,2),           -- 0.00 a 100.00
    ai_justification   TEXT,
    ai_flags           JSONB NOT NULL DEFAULT '[]',
    status_ia          VARCHAR(20) NOT NULL DEFAULT 'pending',

    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT chk_alerts_risk_level
        CHECK (risk_level IN ('low', 'medium', 'high') OR risk_level IS NULL),
    CONSTRAINT chk_alerts_status_ia
        CHECK (status_ia IN ('pending', 'evaluated', 'evaluation_failure')),
    CONSTRAINT chk_alerts_score_range
        CHECK (risk_score IS NULL OR (risk_score >= 0 AND risk_score <= 100)),
    CONSTRAINT chk_alerts_contact_channel
        CHECK (contact_channel in ('ligacao', 'whatsapp', 'sms', 'email'))
);

CREATE INDEX idx_alerts_user_recent
    ON alerts (user_id, created_at DESC);
CREATE INDEX idx_alerts_category ON alerts (scam_category);
CREATE INDEX idx_alerts_risk_recent
    ON alerts (risk_level, created_at DESC)
    WHERE risk_level IS NOT NULL;
CREATE INDEX idx_alerts_ai_flags ON alerts USING GIN (ai_flags); -- o comando gin permite busca dentro do array JSON
CREATE INDEX idx_alerts_transaction_id
    ON alerts (transaction_id)
    WHERE transaction_id IS NOT NULL;
CREATE INDEX idx_scam_patterns_keywords
    ON scam_patterns USING GIN (keywords);
CREATE INDEX idx_alerts_pattern_id
    ON alerts (pattern_id)
    WHERE pattern_id IS NOT NULL;

