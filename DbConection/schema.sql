-- [LGPD] Registro de consentimento / base legal por finalidade (art. 7 e 8)
CREATE TABLE consents (
    id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id        BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    purpose        VARCHAR(80) NOT NULL,          -- ex.: 'analise_antifraude', 'contato_por_sms'
    legal_basis    VARCHAR(30) NOT NULL,
    policy_version VARCHAR(20) NOT NULL,          -- versão da política de privacidade aceita
    granted_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    revoked_at     TIMESTAMPTZ,

    CONSTRAINT chk_consents_legal_basis
        CHECK (legal_basis IN ('consentimento', 'obrigacao_legal', 'execucao_contrato',
                               'legitimo_interesse', 'prevencao_fraude', 'exercicio_direitos')),
    CONSTRAINT chk_consents_revocation
        CHECK (revoked_at IS NULL OR revoked_at >= granted_at)
);
CREATE INDEX idx_consents_user_id ON consents (user_id);

-- [LGPD] Solicitações do titular (art. 18). Prazo padrão de 15 dias (art. 19, II)
CREATE TABLE privacy_requests (
    id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id       BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    request_type  VARCHAR(30) NOT NULL,
    status        VARCHAR(15) NOT NULL DEFAULT 'open',
    requested_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    due_at        TIMESTAMPTZ NOT NULL DEFAULT (now() + INTERVAL '15 days'),
    completed_at  TIMESTAMPTZ,
    notes         TEXT,

    CONSTRAINT chk_privacy_requests_type
        CHECK (request_type IN ('acesso', 'correcao', 'anonimizacao', 'eliminacao',
                                'portabilidade', 'revogacao_consentimento', 'informacao')),
    CONSTRAINT chk_privacy_requests_status
        CHECK (status IN ('open', 'in_progress', 'completed', 'rejected')),
    CONSTRAINT chk_privacy_requests_completion
        CHECK ((status IN ('completed', 'rejected')) = (completed_at IS NOT NULL))
);
CREATE INDEX idx_privacy_requests_user_id ON privacy_requests (user_id);
CREATE INDEX idx_privacy_requests_open ON privacy_requests (due_at)
    WHERE status IN ('open', 'in_progress');

-- [SEG][LGPD] Trilha de auditoria. Guarda SÓ nomes de colunas alteradas, nunca valores pessoais
CREATE TABLE audit_log (
    id               BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    occurred_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    actor            TEXT NOT NULL,
    action           VARCHAR(20) NOT NULL,
    table_name       VARCHAR(63) NOT NULL,
    record_id        TEXT,
    changed_columns  TEXT[],
    purpose          TEXT,

    CONSTRAINT chk_audit_log_action
        CHECK (action IN ('INSERT', 'UPDATE', 'DELETE', 'READ', 'EXPORT', 'ANONYMIZE'))
);
CREATE INDEX idx_audit_log_table_record ON audit_log (table_name, record_id);
CREATE INDEX idx_audit_log_occurred_at  ON audit_log (occurred_at);


-- =====================================================================
-- [SEG][LGPD] AUDITORIA AUTOMÁTICA
-- actor records the authenticated PostgreSQL login (session_user).
-- With a shared application login, it does not identify the end user.
-- =====================================================================
CREATE OR REPLACE FUNCTION trg_audit_row()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $fn$
DECLARE
    v_changed TEXT[];
    v_id      TEXT;
BEGIN
    IF TG_OP = 'INSERT' THEN
        v_id := to_jsonb(NEW)->>'id';
    ELSIF TG_OP = 'DELETE' THEN
        v_id := to_jsonb(OLD)->>'id';
    ELSE
        v_id := to_jsonb(NEW)->>'id';
        SELECT array_agg(n.key ORDER BY n.key) INTO v_changed
        FROM jsonb_each(to_jsonb(NEW)) n
        JOIN jsonb_each(to_jsonb(OLD)) o USING (key)
        WHERE n.value IS DISTINCT FROM o.value
          AND n.key NOT IN ('updated_at', 'verification_attempts');
        IF v_changed IS NULL THEN
            RETURN NULL;   -- só ruído (updated_at / tentativas): não registra
        END IF;
    END IF;

    INSERT INTO audit_log (actor, action, table_name, record_id, changed_columns)
    VALUES (session_user::TEXT,
            TG_OP, TG_TABLE_NAME, v_id, v_changed);
    RETURN NULL;
END;
$fn$;

CREATE TRIGGER users_audit        AFTER INSERT OR UPDATE OR DELETE ON users
    FOR EACH ROW EXECUTE FUNCTION trg_audit_row();
CREATE TRIGGER transactions_audit AFTER INSERT OR UPDATE OR DELETE ON transactions
    FOR EACH ROW EXECUTE FUNCTION trg_audit_row();
CREATE TRIGGER alerts_audit       AFTER INSERT OR UPDATE OR DELETE ON alerts
    FOR EACH ROW EXECUTE FUNCTION trg_audit_row();
CREATE TRIGGER consents_audit AFTER INSERT OR UPDATE OR DELETE ON consents
    FOR EACH ROW EXECUTE FUNCTION trg_audit_row();
CREATE TRIGGER privacy_requests_audit AFTER INSERT OR UPDATE OR DELETE ON privacy_requests
    FOR EACH ROW EXECUTE FUNCTION trg_audit_row();

